#!/usr/bin/env python3
"""Generate CrowPanel LVGL fonts from Montserrat using system FreeType (ctypes).
Run with Python 3.12. Input font and OFL license are supplied by LVGL.
"""
import ctypes as c
from ctypes.util import find_library
from pathlib import Path

class Generic(c.Structure):
    _fields_ = [('data', c.c_void_p), ('finalizer', c.c_void_p)]
class Vector(c.Structure):
    _fields_ = [('x', c.c_long), ('y', c.c_long)]
class BBox(c.Structure):
    _fields_ = [(x, c.c_long) for x in ('xmin', 'ymin', 'xmax', 'ymax')]
class Bitmap(c.Structure):
    _fields_ = [('rows', c.c_uint), ('width', c.c_uint), ('pitch', c.c_int),
                ('buffer', c.POINTER(c.c_ubyte)), ('num_grays', c.c_ushort),
                ('pixel_mode', c.c_ubyte), ('palette_mode', c.c_ubyte), ('palette', c.c_void_p)]
class Slot(c.Structure):
    _fields_ = [('library', c.c_void_p), ('face', c.c_void_p), ('next', c.c_void_p),
                ('glyph_index', c.c_uint), ('generic', Generic), ('metrics', c.c_long * 8),
                ('linearHoriAdvance', c.c_long), ('linearVertAdvance', c.c_long),
                ('advance', Vector), ('format', c.c_uint), ('bitmap', Bitmap),
                ('bitmap_left', c.c_int), ('bitmap_top', c.c_int)]
class Face(c.Structure):
    _fields_ = [(x, c.c_long) for x in ('num_faces','face_index','face_flags','style_flags','num_glyphs')] + [
        ('family_name', c.c_char_p), ('style_name', c.c_char_p), ('num_fixed_sizes', c.c_int),
        ('available_sizes', c.c_void_p), ('num_charmaps', c.c_int), ('charmaps', c.c_void_p),
        ('generic', Generic), ('bbox', BBox), ('units_per_EM', c.c_ushort),
        ('ascender', c.c_short), ('descender', c.c_short), ('height', c.c_short),
        ('max_advance_width', c.c_short), ('max_advance_height', c.c_short),
        ('underline_position', c.c_short), ('underline_thickness', c.c_short),
        ('glyph', c.POINTER(Slot))]

root = Path(__file__).resolve().parents[2]
font = root / '.pio/libdeps/crowpanel/lvgl/scripts/built_in_font/Montserrat-Medium.ttf'
ft = c.CDLL(find_library('freetype'))
ft.FT_Init_FreeType.argtypes = [c.POINTER(c.c_void_p)]
ft.FT_New_Face.argtypes = [c.c_void_p, c.c_char_p, c.c_long, c.POINTER(c.POINTER(Face))]
ft.FT_Set_Pixel_Sizes.argtypes = [c.POINTER(Face), c.c_uint, c.c_uint]
ft.FT_Load_Char.argtypes = [c.POINTER(Face), c.c_ulong, c.c_int32]
ft.FT_Get_Char_Index.argtypes = [c.POINTER(Face), c.c_ulong]
ft.FT_Done_Face.argtypes = [c.POINTER(Face)]
ft.FT_Done_FreeType.argtypes = [c.c_void_p]
lib = c.c_void_p()
assert ft.FT_Init_FreeType(c.byref(lib)) == 0
face = c.POINTER(Face)()
assert ft.FT_New_Face(lib, str(font).encode(), 0, c.byref(face)) == 0
ranges = [(0x20,0x7f),(0xa0,0x17f),(0x400,0x4ff)]
for size in (14,18,22):
    assert ft.FT_Set_Pixel_Sizes(face, 0, size) == 0
    data = []; desc = ['{0}']; cmaps = []; top = bottom = 0
    for start,end in ranges:
        first = len(desc)
        for code in range(start,end+1):
            assert ft.FT_Load_Char(face, code, 4) == 0  # FT_LOAD_RENDER, grayscale
            glyph = face.contents.glyph.contents
            bm = glyph.bitmap
            assert bm.pixel_mode == 2 or not bm.width
            offset = len(data)
            pixels = [round(bm.buffer[y*bm.pitch+x]*15/255) for y in range(bm.rows) for x in range(bm.width)]
            if len(pixels)%2: pixels.append(0)
            data.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
            desc.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}' %
                        (offset,round(glyph.advance.x/4),bm.width,bm.rows,glyph.bitmap_left,glyph.bitmap_top-bm.rows))
            top=max(top,glyph.bitmap_top);bottom=max(bottom,bm.rows-glyph.bitmap_top)
        cmaps.append('{.range_start=%d,.range_length=%d,.glyph_id_start=%d,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}' % (start,end-start+1,first))
    name=f'lv_font_crowpanel_{size}'
    output = '/* Generated by tools/fonts/crowpanel_fonts.py from Montserrat-Medium.ttf (OFL). */\n#ifdef RSCROWPANEL\n#include <lvgl.h>\n'
    output += 'static const uint8_t bitmap[]={\n' + '\n'.join(','.join(map(str,data[i:i+24]))+',' for i in range(0,len(data),24))+'\n};\n'
    output += 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={\n'+',\n'.join(desc)+'\n};\n'
    output += 'static const lv_font_fmt_txt_cmap_t cmaps[]={\n'+',\n'.join(cmaps)+'\n};\n'
    output += 'static lv_font_fmt_txt_glyph_cache_t cache;\nstatic const lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=3,.bpp=4,.cache=&cache};\n'
    output += f'const lv_font_t {name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={top+bottom},.base_line={bottom},.underline_position=-2,.underline_thickness=1,.dsc=&dsc}};\n#endif\n'
    (root / f'src/ui/lvgl/fonts/{name}.c').write_text(output)
    print(name, 'line height',top+bottom,'bitmap bytes',len(data))
ft.FT_Done_Face(face);ft.FT_Done_FreeType(lib)
